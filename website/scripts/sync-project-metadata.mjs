import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = path.join(root, 'project-metadata.json');
const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
const parent = path.resolve(root, '..');
const versionPath = path.join(parent, 'VERSION');
const manifestPath = path.join(parent, 'RELEASE_MANIFEST.json');

let metadata = { ...snapshot };
if (fs.existsSync(manifestPath)) {
  try {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    const manifestVersion = manifest.version ?? manifest.release?.version;
    if (manifestVersion) metadata.version = manifestVersion;
  } catch {
    console.warn('RELEASE_MANIFEST.json is unreadable; keeping standalone snapshot.');
  }
}
if (fs.existsSync(versionPath)) {
  const version = fs.readFileSync(versionPath, 'utf8').trim();
  if (version) metadata.version = version;
}

const releaseSource = `// Generated by scripts/sync-project-metadata.mjs. Do not hand-edit release facts.\nexport const release = ${JSON.stringify({
  version: metadata.version,
  status: metadata.status,
  skillCount: metadata.skillCount,
  workflowCount: metadata.workflowCount,
  providerCount: metadata.providerCount,
  firstClassProviderCount: metadata.firstClassProviderCount,
  evalCount: metadata.evalCount,
  agentOsVersion: metadata.agentOsVersion,
  gsdVersion: metadata.gsdVersion,
}, null, 2).replace(/"([^"]+)":/g, '$1:')} as const;\n\nexport const releaseFacts = [\n  [String(release.skillCount), 'Agent Skills'],\n  [String(release.workflowCount), 'workflows'],\n  [String(release.providerCount), 'provider targets'],\n  [String(release.evalCount), 'deterministic evals'],\n] as const;\n`;
fs.writeFileSync(path.join(root, 'src/data/release.generated.ts'), releaseSource);
console.log(`Synchronized website metadata for PlanOnce v${metadata.version}.`);
